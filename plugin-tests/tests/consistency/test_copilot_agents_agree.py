"""The Copilot CLI copy of each helper agent must stay in step with its Claude Code agent.

An Agent Plugins 1.0 plugin keeps Copilot custom agents in `com.github.copilot/agents/`, a
location GitHub's docs fix, so Copilot cannot read the Claude files in `agents/`. The second copy is
generated by `plugin-tests/scripts/sync_copilot_agents.py`; these tests fail when a copy drifts from
its source. NOT tested against a live Copilot CLI (none is installed): they pin the shape the docs
describe and say nothing about whether Copilot loads the agents.

Sources, read raw from github/docs: content/copilot/reference/custom-agents-configuration.md
(frontmatter fields, tool aliases) and copilot-cli-reference/cli-plugin-reference.md (the
`com.github.copilot/agents/` location).
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

import sync_copilot_agents as sync

_PLUGIN_ROOT = sync.PLUGIN_ROOT
_CLAUDE = sync.CLAUDE_DIR
_COPILOT = sync.COPILOT_DIR
# The frontmatter fields the copies may carry: all four are in the custom agents configuration
# reference's property table. `color` is Claude Code's and Copilot's table has no such field.
_COPILOT_FIELDS = ("name", "description", "tools", "model")
# The tool aliases a read-only reviewer may be granted: `read` and `search` (Grep, Glob).
_READ_ONLY_TOOLS = {"read", "search"}


def _parts(text: str) -> tuple[dict[str, str], str]:
    """Frontmatter as {key: raw value}, and the body, parsed independently of the generator."""
    match = re.fullmatch(r"---\n(.*?)\n---\n(.*)", text, flags=re.DOTALL)
    assert match, "no '---' frontmatter fence"
    fields = {}
    for line in match.group(1).split("\n"):
        key, _, value = line.partition(":")
        fields[key] = value.strip()
    return fields, match.group(2)


def _claude_agents() -> dict[str, str]:
    return {p.stem: p.read_text(encoding="utf-8") for p in sorted(_CLAUDE.glob("*.md"))}


def _copilot_agents() -> dict[str, str]:
    return {p.name.removesuffix(".agent.md"): p.read_text(encoding="utf-8")
            for p in sorted(_COPILOT.glob("*"))}


# requirement: plugin-distribution / Helper agents in GitHub Copilot CLI
def test_every_claude_agent_has_a_copilot_copy_and_no_copy_is_orphaned():
    claude, copilot = set(_claude_agents()), set(_copilot_agents())
    assert claude, "no Claude agents found; the test would pass on nothing"
    assert not claude - copilot, (
        f"no Copilot copy for {sorted(claude - copilot)}; run "
        "`python3 plugin-tests/scripts/sync_copilot_agents.py --write`"
    )
    assert not copilot - claude, (
        f"Copilot copies with no Claude agent: {sorted(copilot - claude)}; delete those files "
        "(`python3 plugin-tests/scripts/sync_copilot_agents.py --write` removes them)"
    )
    assert all(p.name.endswith(".agent.md") for p in _COPILOT.glob("*")), (
        "every file in the Copilot agents directory must be <name>.agent.md"
    )


# requirement: plugin-distribution / Helper agents in GitHub Copilot CLI
def test_each_copilot_copy_has_the_same_instructions_and_description_as_its_claude_agent():
    """Read independently of the generator, so a bug in `render` cannot hide a drift."""
    copilot = _copilot_agents()
    for name, claude_text in _claude_agents().items():
        c_fields, c_body = _parts(claude_text)
        p_fields, p_body = _parts(copilot[name])
        assert p_body == c_body, (
            f"{name}: the Copilot copy's instructions differ from agents/{name}.md; edit the "
            "Claude agent and run `python3 plugin-tests/scripts/sync_copilot_agents.py --write`"
        )
        assert p_fields["name"] == c_fields["name"] == name
        assert p_fields["description"] == c_fields["description"], f"{name}: description differs"


# requirement: plugin-distribution / Helper agents in GitHub Copilot CLI
def test_each_copilot_copy_is_exactly_what_the_generator_produces():
    copilot = _copilot_agents()
    for filename, expected in sync.expected_copies().items():
        name = filename.removesuffix(".agent.md")
        assert copilot[name] == expected, (
            f"{name}: the committed Copilot copy is not what sync_copilot_agents.py renders; "
            "run `python3 plugin-tests/scripts/sync_copilot_agents.py --write`"
        )


# requirement: plugin-distribution / Helper agents in GitHub Copilot CLI
def test_a_copilot_copy_grants_only_the_read_only_tools_its_claude_agent_has():
    for name, text in _copilot_agents().items():
        fields, _ = _parts(text)
        assert set(fields) <= set(_COPILOT_FIELDS), (
            f"{name}: frontmatter fields outside {_COPILOT_FIELDS}: {sorted(set(fields) - set(_COPILOT_FIELDS))}"
        )
        tools = json.loads(fields["tools"])
        assert tools, (
            f"{name}: an empty tools list disables every tool, and an absent one grants all of them"
        )
        assert set(tools) <= _READ_ONLY_TOOLS, (
            f"{name}: Copilot tools {tools} exceed the read-only set {sorted(_READ_ONLY_TOOLS)}"
        )
    for name, text in _claude_agents().items():
        claude_tools = json.loads(_parts(text)[0]["tools"])
        mapped = json.loads(_parts(_copilot_agents()[name])[0]["tools"])
        assert mapped == sync.map_tools(claude_tools)
        assert {t.lower() for t in claude_tools} <= {"read", "grep", "glob"}, (
            f"{name}: a Claude tool outside Read/Grep/Glob needs a deliberate Copilot mapping"
        )


def test_each_copilot_model_matches_the_generators_model_map():
    """The IDs themselves are from the CLI reference's supported-models table and are NOT
    checked against it here; this pins that a copy carries the map's ID for its alias."""
    for name, text in _claude_agents().items():
        alias = _parts(text)[0]["model"]
        assert alias in sync.MODEL_MAP, f"{name}: model {alias!r} has no Copilot mapping"
        assert _parts(_copilot_agents()[name])[0]["model"] == sync.MODEL_MAP[alias]


def test_the_generator_refuses_what_it_cannot_map_instead_of_dropping_it():
    base = '---\nname: x\ndescription: "d"\nmodel: sonnet\ncolor: blue\ntools: ["Read"]\n---\nBody\n'
    assert sync.render(base) == (
        '---\nname: x\ndescription: "d"\nmodel: claude-sonnet-5.5\ntools: ["read"]\n---\nBody\n'
    )
    # Copilot ignores a tool name it does not know, which would silently shrink the tool set.
    for broken in (base.replace('["Read"]', '["Frobnicate"]'),
                   base.replace("sonnet", "turbo"),
                   base.replace("color: blue", "permissionMode: plan")):
        with pytest.raises(ValueError):
            sync.render(broken)
    # A Claude agent with no `tools` line inherits every tool, and so would its copy.
    for missing in (base.replace('tools: ["Read"]\n', ""), base.replace("model: sonnet\n", "")):
        with pytest.raises(ValueError, match="no '(tools|model)' line"):
            sync.render(missing)
    # A shell tool maps faithfully, so the read-only test above is what stops it shipping.
    assert sync.map_tools(["Read", "Bash", "Grep", "Glob"]) == ["read", "execute", "search"]


_AGENT = '---\nname: a\ndescription: "d"\nmodel: sonnet\ntools: ["Read"]\n---\nBody\n'


def _seed(monkeypatch, tmp_path: Path) -> tuple[Path, Path]:
    """One Claude agent and its up-to-date copy in a throwaway pair of directories."""
    claude, copilot = tmp_path / "agents", tmp_path / "copilot"
    claude.mkdir()
    copilot.mkdir()
    (claude / "a.md").write_text(_AGENT, encoding="utf-8", newline="\n")
    (copilot / "a.agent.md").write_text(sync.render(_AGENT), encoding="utf-8", newline="\n")
    monkeypatch.setattr(sync, "CLAUDE_DIR", claude)
    monkeypatch.setattr(sync, "COPILOT_DIR", copilot)
    return claude, copilot


def test_the_generator_reports_an_orphaned_copy_and_write_deletes_it(monkeypatch, tmp_path, capsys):
    _, copilot = _seed(monkeypatch, tmp_path)
    assert sync.main([]) == 0
    (copilot / "gone.agent.md").write_text("x\n", encoding="utf-8")
    (copilot / "stray.txt").write_text("x\n", encoding="utf-8")
    capsys.readouterr()
    assert sync.main([]) == 1
    err = capsys.readouterr().err
    assert "gone.agent.md" in err and "stray.txt" in err, err
    assert (copilot / "gone.agent.md").exists(), "check mode must not delete anything"
    assert sync.main(["--write"]) == 0
    assert sorted(p.name for p in copilot.iterdir()) == ["a.agent.md"]
    assert "deleted" in capsys.readouterr().out
    assert sync.main([]) == 0


def test_the_generator_fixes_a_stale_copy_and_an_orphan_in_one_write(monkeypatch, tmp_path):
    _, copilot = _seed(monkeypatch, tmp_path)
    (copilot / "a.agent.md").write_text("stale\n", encoding="utf-8")
    (copilot / "old.agent.md").write_text("x\n", encoding="utf-8")
    assert sync.main([]) == 1
    assert sync.main(["--write"]) == 0
    assert (copilot / "a.agent.md").read_text(encoding="utf-8") == sync.render(_AGENT)
    assert not (copilot / "old.agent.md").exists()


def test_the_generator_runs_when_the_copilot_directory_does_not_exist(monkeypatch, tmp_path):
    _, copilot = _seed(monkeypatch, tmp_path)
    for path in copilot.iterdir():
        path.unlink()
    copilot.rmdir()
    assert sync.main([]) == 1
    assert sync.main(["--write"]) == 0
    assert (copilot / "a.agent.md").is_file()


def test_the_install_docs_say_the_agents_are_offered_and_the_guard_hooks_do_not_run():
    """The agent copies are offered to Copilot and the guards are not. A reader choosing
    Copilot must not assume a guard protects them."""
    repo = _PLUGIN_ROOT.parents[2]
    for doc in ("README.md", "DEVELOPER-GUIDE.md"):
        text = (repo / doc).read_text(encoding="utf-8")
        assert "guard hooks do not run in Copilot" in text, f"{doc} must say the guard hooks do not run in Copilot"
    # Whitespace-joined, since the prose wraps lines. The agents paragraph names the directory and
    # says so itself: it must carry its own "untested" sentence, not lean on the section heading.
    readme = " ".join((repo / "README.md").read_text(encoding="utf-8").split())
    paragraph = readme[readme.index("com.github.copilot/agents/"):]
    assert "untested in a live Copilot CLI" in paragraph.split("guard hooks do not run")[0]


# requirement: plugin-distribution / Helper agents in GitHub Copilot CLI
def test_the_claude_install_does_not_load_the_copilot_copies():
    """Claude Code discovers agents in `agents/` only; the copies must never sit there, and the
    Claude manifest must not point at the Copilot directory."""
    assert not list(_CLAUDE.glob("*.agent.md")), "a Copilot copy sits in the Claude agents directory"
    claude_manifest = json.loads((_PLUGIN_ROOT / ".claude-plugin" / "plugin.json").read_text(encoding="utf-8"))
    assert "agents" not in claude_manifest, "the Claude manifest would need to be checked for double loading"
    root_manifest = json.loads((_PLUGIN_ROOT / "plugin.json").read_text(encoding="utf-8"))
    assert "agents" not in root_manifest, (
        "Agent Plugins 1.0 has no component path fields; Copilot reads com.github.copilot/agents/"
    )
